int fs(int u)
{
    if(u == par[u]) return u;
    else return par[u] = fs(par[u]);
}
bool join(int u, int v)
{
    u = fs(u); v = fs(v);
    if(u == v) return false;
    if(sz[u] < sz[v]) swap(u, v);
    par[v] = u;
    sz[u] += sz[v];
    return true;
}
